INSERT INTO dim_date
SELECT TO_NUMBER(TO_CHAR(d,'YYYYMMDD')),
       d,
       TRIM(TO_CHAR(d,'Day','NLS_DATE_LANGUAGE=ENGLISH')),
       EXTRACT(DAY FROM d),
       TO_NUMBER(TO_CHAR(d,'YYYYMM')),
       EXTRACT(MONTH FROM d),
       TRIM(TO_CHAR(d,'Month','NLS_DATE_LANGUAGE=ENGLISH')),
       TO_CHAR(d,'Mon YYYY','NLS_DATE_LANGUAGE=ENGLISH'),
       TO_NUMBER(TO_CHAR(d,'YYYYQ')),
       'Q'||TO_CHAR(d,'Q')||' '||TO_CHAR(d,'YYYY'),
       EXTRACT(YEAR FROM d)
FROM (SELECT DATE '2023-01-01' + LEVEL - 1 AS d FROM dual CONNECT BY LEVEL <= 1096);
COMMIT;
